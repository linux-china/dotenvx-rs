use clap::ArgMatches;
use crate::commands::shell_single_quote;
use colored::Colorize;
use std::fs::Permissions;
use std::path::{Path, PathBuf};
use symlink::symlink_file;

pub fn link_command(command_matches: &ArgMatches, dotenvx_name: &str) {
    let command_name = command_matches
        .get_one::<String>("command")
        .map(|s| s.as_str())
        .unwrap();
    if command_name.ends_with("venv/bin/python") {
        link_uv_python(command_name);
        return;
    }
    let target_path = PathBuf::from(command_name);
    if target_path.exists() {
        eprintln!("The target path already exists: {}", target_path.display());
        std::process::exit(1);
    }
    if let Some(parent) = target_path.parent() {
        if !parent.exists() {
            std::fs::create_dir_all(parent).unwrap();
        }
    }
    let dotenvx_path = if dotenvx_name.contains("/") || dotenvx_name.contains("\\") {
        PathBuf::from(dotenvx_name)
    } else {
        which::which(dotenvx_name).unwrap()
    };
    symlink_file(dotenvx_path, target_path).unwrap();
    println!(
        "{}",
        format!("${command_name} created and linked to dotenvx executable").green()
    );
}

/// Marker comment placed in python wrappers generated by `dotenvx link`.
const PYTHON_WRAPPER_MARKER: &str = "# dotenvx-python-wrapper";

#[derive(Debug, PartialEq, Eq)]
enum LinkOutcome {
    Replaced,
    AlreadyLinked,
}

fn link_uv_python(command_name: &str) {
    match replace_python_with_wrapper(Path::new(command_name)) {
        Ok(LinkOutcome::Replaced) => {
            println!("{command_name} replaced with dotenvx and python3");
        }
        Ok(LinkOutcome::AlreadyLinked) => {
            println!("{command_name} is already a dotenvx wrapper, nothing to do");
        }
        Err(e) => {
            eprintln!("{}", e.red());
            std::process::exit(1);
        }
    }
}

/// Replaces a venv `python` symlink with a bash wrapper that loads `.env` via dotenvx
/// before exec'ing the real interpreter.
///
/// Only symlinks are replaced: a regular file is either a wrapper generated earlier
/// (left untouched, so the wrapper never ends up exec'ing itself) or something we
/// don't recognize (refused).
fn replace_python_with_wrapper(python_path: &Path) -> Result<LinkOutcome, String> {
    let display = python_path.display();
    let metadata = std::fs::symlink_metadata(python_path)
        .map_err(|e| format!("Failed to read {display}: {e}"))?;
    if !metadata.file_type().is_symlink() {
        let is_wrapper = std::fs::read(python_path)
            .map(|bytes| String::from_utf8_lossy(&bytes).contains(PYTHON_WRAPPER_MARKER))
            .unwrap_or(false);
        return if is_wrapper {
            Ok(LinkOutcome::AlreadyLinked)
        } else {
            Err(format!(
                "{display} is not a symlink, refusing to replace it with a dotenvx wrapper"
            ))
        };
    }
    let real_path = std::fs::canonicalize(python_path)
        .map_err(|e| format!("Failed to resolve symlink {display}: {e}"))?;
    let python3_script = format!(
        r#"#!/bin/bash
{PYTHON_WRAPPER_MARKER}

# load .env by dotenvx
eval "$( dotenvx decrypt --stdout --format shell )"
# Execute python3 command with arguments
exec {} "$@"
"#,
        shell_single_quote(&real_path.to_string_lossy())
    );
    std::fs::remove_file(python_path).map_err(|e| format!("Failed to remove {display}: {e}"))?;
    std::fs::write(python_path, python3_script)
        .map_err(|e| format!("Failed to write {display}: {e}"))?;
    set_executable(python_path);
    Ok(LinkOutcome::Replaced)
}

#[cfg(unix)]
fn set_executable<P: AsRef<Path>>(path: P) {
    use std::os::unix::fs::PermissionsExt;
    std::fs::set_permissions(path, Permissions::from_mode(0o755)).unwrap();
}

#[cfg(not(unix))]
fn set_executable<P: AsRef<Path>>(path: P) {}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use std::os::unix::fs::symlink;

    fn make_venv() -> (tempfile::TempDir, PathBuf, PathBuf) {
        let dir = tempfile::tempdir().unwrap();
        let real = dir.path().join("python3.12");
        std::fs::write(&real, "#!/bin/sh\necho real\n").unwrap();
        let bin = dir.path().join(".venv/bin");
        std::fs::create_dir_all(&bin).unwrap();
        let python = bin.join("python");
        symlink(&real, &python).unwrap();
        (dir, python, real.canonicalize().unwrap())
    }

    #[test]
    fn test_link_twice_does_not_create_recursive_wrapper() {
        let (_dir, python, real) = make_venv();
        assert_eq!(replace_python_with_wrapper(&python), Ok(LinkOutcome::Replaced));
        let first = std::fs::read_to_string(&python).unwrap();
        assert!(first.contains(PYTHON_WRAPPER_MARKER));
        assert!(first.contains(&format!("exec '{}' \"$@\"", real.display())));
        assert!(first.contains(r#"eval "$( dotenvx decrypt --stdout --format shell )""#));

        assert_eq!(replace_python_with_wrapper(&python), Ok(LinkOutcome::AlreadyLinked));
        assert_eq!(std::fs::read_to_string(&python).unwrap(), first);
    }

    #[test]
    fn test_link_refuses_regular_file() {
        let (_dir, python, _real) = make_venv();
        std::fs::remove_file(&python).unwrap();
        std::fs::write(&python, "not a symlink").unwrap();
        assert!(replace_python_with_wrapper(&python).is_err());
        assert_eq!(std::fs::read_to_string(&python).unwrap(), "not a symlink");
    }

    #[test]
    fn test_link_broken_symlink_is_error() {
        let (_dir, python, real) = make_venv();
        std::fs::remove_file(&real).unwrap();
        assert!(replace_python_with_wrapper(&python).is_err());
        assert!(std::fs::symlink_metadata(&python).unwrap().file_type().is_symlink());
    }
}
